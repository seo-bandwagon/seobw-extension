// SEO Bandwagon — Google Search Console row actions (runner)
//
// Loads after src/lib/gsc-inject.js (manifest content_scripts order). Watches
// the Performance report (GSC is an SPA) and adds two icons to each data row:
// "Open in Google Search" (new tab) and "Open in Google Search (private
// window)". The worker owns window/tab creation; when the browser refuses an
// incognito window (the extension is not allowed in Private/Incognito), the
// worker falls back to a normal window and tells us, and we show a one-time
// hint explaining how to enable it.

(function () {
  'use strict';

  if (window.__seoBwGscSerpLoaded) return;
  window.__seoBwGscSerpLoaded = true;

  const inject = window.SBWGscInject;
  if (!inject) return;
  const compare = window.SBWGscCompare;

  let hinted = false;
  function hint(text) {
    if (hinted) return;
    hinted = true;
    const el = document.createElement('div');
    el.className = 'seo-bw-gsc-toast';
    el.setAttribute('role', 'status');
    el.textContent = text;
    document.body.appendChild(el);
    setTimeout(() => el.remove(), 9000);
  }

  // 1.10.2: searches open in the property's country, with personalisation
  // off (the worker adds pws=0), closer to what the report counts.
  const handlers = {
    open(query) {
      chrome.runtime.sendMessage({ action: 'openSearch', query, gl: inject.propertyCountry(location) });
    },
    openPrivate(query) {
      chrome.runtime.sendMessage({ action: 'openIncognitoSearch', query, gl: inject.propertyCountry(location) }, (res) => {
        if (chrome.runtime.lastError) return;
        if (res && res.ok && res.incognito === false) {
          hint(
            'Opened in a normal window: this browser does not let SEO Bandwagon open private windows. ' +
              'Enable "Allow in Private" (Brave) or "Allow in Incognito" (Chrome) for the extension on the extensions page.',
          );
        }
      });
    },
  };

  function ensureStyles() {
    if (document.getElementById('seo-bw-gsc-styles')) return;
    const style = document.createElement('style');
    style.id = 'seo-bw-gsc-styles';
    style.textContent = inject.CSS + (compare ? compare.CSS : '');
    (document.head || document.documentElement).appendChild(style);
  }

  function scan() {
    if (!/\/performance\b/.test(location.pathname)) {
      // Left the report entirely; take our icons with us.
      inject.removeAll(document);
      return;
    }
    // Queries tab only: on Pages/Countries/Devices/Dates/Search appearance
    // the first cell is not a search query, so strip anything we injected
    // before the SPA swapped the table in place. isQueriesView abstains to
    // "no" when it cannot identify the tab, so removeAll runs on any doubt.
    // The compare-mode math applies on every dimension tab — the metric
    // cards and the % change column mean the same thing for pages, countries
    // and devices — so only the row icons are gated.
    ensureStyles();
    if (inject.isQueriesView(location, document)) inject.injectAll(document, handlers);
    else inject.removeAll(document);
    if (compare) compare.apply(document);
  }

  // fix-1 item 1b (CRITICAL): the runner must ignore mutations it caused
  // itself, or a MutationObserver-driven scan()->inject->mutate->scan() loop
  // never settles. Two guards, belt-and-suspenders:
  //  (1) `injecting` is true for the duration of every scan() call (and for
  //      one more macrotask after it, via setTimeout(...,0)) so mutation
  //      records generated by that scan() are dropped outright, regardless
  //      of which nodes they touch.
  //  (2) even outside that window, a mutation batch whose every record is
  //      confined to nodes we ourselves mark (a marked node itself, or an
  //      added/removed node that is one of ours) is ignored -- this covers
  //      an in-place update to something we already injected (e.g. a badge
  //      re-rendering with the same or changed text) without suppressing a
  //      batch where GSC's own content changed too.
  const OWN_MARKER_SELECTOR = '[data-seo-bw-compare], .seo-bw-cmp-tools, .seo-bw-cmp-summary, .seo-bw-gsc-actions';

  function nodeMatchesOwnMarker(node) {
    if (!node) return false;
    const el = node.nodeType === 1 ? node : node.parentElement;
    if (!el || typeof el.closest !== 'function') return false;
    return !!el.closest(OWN_MARKER_SELECTOR);
  }

  function isOwnElement(node) {
    return node.nodeType === 1 && typeof node.matches === 'function' && node.matches(OWN_MARKER_SELECTOR);
  }

  function recordIsOwnMutation(record) {
    if (nodeMatchesOwnMarker(record.target)) return true;
    const changed = Array.prototype.slice.call(record.addedNodes || []).concat(Array.prototype.slice.call(record.removedNodes || []));
    if (changed.length === 0) return false;
    return changed.every((n) => isOwnElement(n) || nodeMatchesOwnMarker(n));
  }

  let scheduled = false;
  let injecting = false;
  // A GSC re-render that lands in the microtask right after scan() would be
  // indistinguishable from our own mutations by timing alone; the own-node
  // filter runs FIRST so it is recognised as foreign, and if it arrives while
  // `injecting` is still set we remember it and scan once more afterwards.
  // Safe because apply() is a true no-op on unchanged state, so the extra
  // scan terminates in one pass.
  let missed = false;

  // requestAnimationFrame coalesces a burst of mutations into one scan. It is
  // always present in a real content script; the setTimeout fallback is for
  // contexts that lack it (a detached document during teardown, for one),
  // where throwing would surface as an uncaught error from the observer.
  const nextFrame =
    typeof requestAnimationFrame === 'function'
      ? requestAnimationFrame
      : (fn) => setTimeout(fn, 16);

  function schedule() {
    if (scheduled) return;
    scheduled = true;
    nextFrame(() => {
      scheduled = false;
      runScan();
    });
  }

  function runScan() {
    injecting = true;
    scan();
    // Let the (synchronous) MutationObserver microtask for the mutations
    // scan() just made fire and get dropped by the `injecting` guard above
    // before flipping it back off on the next macrotask.
    setTimeout(() => {
      injecting = false;
      if (missed) {
        missed = false;
        schedule();
      }
    }, 0);
  }

  const observer = new MutationObserver((records) => {
    if (records.length && records.every(recordIsOwnMutation)) return;
    if (injecting) {
      missed = true;
      return;
    }
    schedule();
  });
  // Module-scoped; the test harness reaches it through the hook below only.
  if (window.__seoBwGscSerpObserver) window.__seoBwGscSerpObserver.disconnect();
  Object.defineProperty(window, '__seoBwGscSerpObserver', { value: observer, configurable: true, enumerable: false, writable: true });
  observer.observe(document.documentElement, { childList: true, subtree: true });

  // Search Console is an SPA: clicking Pages changes the URL, and the DOM
  // change that follows may be recycled rows the own-node filter treats as
  // ours. Without this the icons survived the tab switch until some unrelated
  // mutation happened to fire. Watch navigation directly instead of hoping
  // for a mutation: popstate for back/forward, and for the tab clicks the
  // worker's webNavigation.onHistoryStateUpdated ('gscNavigated'). Until
  // 1.10.2 this patched history.pushState, but a content script runs in an
  // isolated world: the page's own pushState calls never reached the patch.
  function onNavigated() {
    // Strip immediately rather than waiting for the next frame, so the icons
    // never render over a table that is no longer Queries.
    if (!inject.isQueriesView(location, document)) inject.removeAll(document);
    schedule();
  }

  window.addEventListener('popstate', onNavigated);
  if (typeof chrome !== 'undefined' && chrome.runtime && chrome.runtime.onMessage) {
    chrome.runtime.onMessage.addListener((msg) => {
      if (msg && msg.action === 'gscNavigated') onNavigated();
    });
  }

  runScan();
})();
